// Import public OSM data downloaded with the Bali administrative-area query.
const fs=require('node:fs');
const P=require('../dist/core.js');
const raw=JSON.parse(fs.readFileSync(process.argv[2]||'.local/osm-fuel.json','utf8'));
const boundary=JSON.parse(fs.readFileSync('.local/bali-boundary.json','utf8'));
function inRing(p,ring){let inside=false;for(let i=0,j=ring.length-1;i<ring.length;j=i++){const a=ring[i],b=ring[j];if((a[1]>p[1])!==(b[1]>p[1])&&p[0]<(b[0]-a[0])*(p[1]-a[1])/(b[1]-a[1])+a[0])inside=!inside;}return inside;}
function inBali(p){const polygons=boundary.type==='Polygon'?[boundary.coordinates]:boundary.coordinates;return polygons.some(rings=>inRing(p,rings[0])&&!rings.slice(1).some(r=>inRing(p,r)));}
if(raw.remark||!raw.elements?.length)throw Error('Incomplete Overpass response');
const seeds=JSON.parse(fs.readFileSync('scripts/seed-stations.json','utf8'));
const areas=[
 ['nusa-dua','Nusa Dua / Benoa',115.210,-8.798,6],['jimbaran','Jimbaran',115.171,-8.781,6],['uluwatu','Uluwatu / Ungasan',115.132,-8.824,8],
 ['kuta','Kuta',115.173,-8.723,3.5],['legian','Legian',115.171,-8.706,2.5],['seminyak','Seminyak',115.166,-8.688,3.5],
 ['canggu','Canggu',115.139,-8.647,4],['pererenan','Pererenan',115.124,-8.644,3.5],['denpasar','Denpasar',115.216,-8.655,8],['sanur','Sanur',115.262,-8.689,5],
 ['ubud','Ubud',115.263,-8.507,7],['gianyar','Gianyar',115.326,-8.542,9],['sukawati','Sukawati',115.283,-8.600,5],
 ['mengwi','Mengwi',115.171,-8.545,8],['tabanan','Tabanan',115.128,-8.540,10],['bangli','Bangli',115.355,-8.455,12],['kintamani','Kintamani',115.327,-8.242,18],
 ['klungkung','Klungkung',115.405,-8.535,10],['candidasa','Candidasa',115.568,-8.507,12],['karangasem','Karangasem',115.614,-8.447,15],['amed','Amed / Tulamben',115.629,-8.335,15],
 ['singaraja','Singaraja',115.089,-8.112,15],['lovina','Lovina',115.024,-8.161,12],['pemuteran','Pemuteran',114.658,-8.145,18],['negara','Negara / West Bali',114.624,-8.356,25],
 ['penida','Nusa Penida',115.551,-8.724,18],['lembongan','Nusa Lembongan',115.450,-8.684,5]
].map(([id,name,lng,lat,radius])=>({id,name,center:[lng,lat],radius}));
const approachSeeds={
 'nusa-dua':[115.2205,-8.7996],'bypass-30x':[115.1973,-8.7856],'bypass-27':[115.2069,-8.7860],
 'dharmawangsa':[115.1928,-8.8108],'jimbaran-02':[115.1790,-8.7620]
};
const nearestArea=coords=>[...areas].sort((a,b)=>P.distance(coords,a.center)-P.distance(coords,b.center))[0];
const stations=seeds.map(s=>({...s,approachStart:approachSeeds[s.id]}));
let duplicates=0;
for(const item of raw.elements){
 const t=item.tags||{},p=item.center||item,coordinates=[p.lon,p.lat];
 if(!coordinates.every(Number.isFinite)||!inBali(coordinates)||t.disused==='yes'||t.abandoned==='yes'||t.access==='private')continue;
 if(stations.some(s=>P.distance(s.coordinates,coordinates)<.065)){duplicates++;continue;}
 const area=nearestArea(coordinates),name=(t.name||t.brand||t.operator||'Fuel station').trim();
 const street=t['addr:street']||'',address=[street,t['addr:housenumber'],t['addr:suburb'],t['addr:city']].filter(Boolean).join(', ');
 const specific=/\d|SPBU|Pertashop|Pertamini/i.test(name)||name.length>14;
 const shortName=specific?name:street?name+' · '+street:name+' · '+area.name;
 stations.push({id:'osm-'+item.type+'-'+item.id,name,shortName,coordinates,address:address||'Near '+area.name,area:area.name,placeId:null,
  source:'OpenStreetMap',sourceUrl:'https://www.openstreetmap.org/'+item.type+'/'+item.id,operatingStatus:'unknown',operatingSource:'unknown',operatingCheckedAt:null,
  // One reproducible candidate approach; Google snaps it to its road network.
  // Measurement validates the station endpoint and available traffic coverage.
  approachStart:[Number(p.lon.toFixed(7)),Number((p.lat+.012).toFixed(7))]});
}
const catalogue={importedAt:new Date().toISOString(),sourceDate:raw.osm3s?.timestamp_osm_base,areas,stations};
fs.writeFileSync('dist/stations.json',JSON.stringify(catalogue,null,2)+'\n');
fs.writeFileSync('traffic-service/stations.mjs','// Generated by scripts/import-stations.cjs from the public station catalogue.\nexport default '+JSON.stringify(stations.map(s=>({id:s.id,end:s.coordinates,start:s.approachStart})))+';\n');
console.log(JSON.stringify({stations:stations.length,duplicates,areas:areas.map(a=>({area:a.name,count:stations.filter(s=>P.distance(s.coordinates,a.center)<=a.radius).length}))},null,2));
